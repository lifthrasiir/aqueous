/* Prints the CRC-32 of the setup header libvorbis's VBR setup makes, scanning quality.
   usage: setups OUTDIR CH RATE QLO QHI QSTEP [COUPLING [LOWPASS_KHZ]] -- prints
   "rate ch q crc" when the setup changes and writes OUTDIR/<crc>.bin for each new one.
   COUPLING 0 or 1 sets OV_ECTL_COUPLING_SET, LOWPASS_KHZ > 0 sets OV_ECTL_LOWPASS_SET; -1 leaves
   either at its default. Uses only the public libvorbis API.

   The oracle of vorbis_setups.py. Build it against a libvorbis tree and libogg (for the bit
   packer) without their build systems, e.g.
     gcc -O2 -w -I$OGG/include -I$VORBIS/include -I$VORBIS/lib vorbis_setups_harness.c \
       $OGG/src/bitwise.c $OGG/src/framing.c \
       $(ls $VORBIS/lib/*.c | grep -v -E 'barkmel|psytune|tone|vorbisfile') -o harness -lm
   (libogg's include/ogg/config_types.h is generated by its configure; write it by hand with
   <stdint.h> typedefs if needed.) */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <vorbis/vorbisenc.h>

static unsigned long crc_table[256];

static unsigned long crc32(const unsigned char *p, long n) {
  unsigned long c = 0xffffffffUL;
  while (n--) c = crc_table[(c ^ *p++) & 0xff] ^ (c >> 8);
  return c ^ 0xffffffffUL;
}

static int coupling = -1;
static double lowpass = -1;

/* The setup's CRC; *ok is 0 if libvorbis refuses the parameters. */
static unsigned long setup(const char *dir, int ch, long rate, float q, int *ok) {
  vorbis_info vi;
  vorbis_comment vc;
  vorbis_dsp_state vd;
  ogg_packet h, hc, hs;
  unsigned long c = 0;
  vorbis_info_init(&vi);
  *ok = vorbis_encode_setup_vbr(&vi, ch, rate, q) == 0;
#ifdef OV_ECTL_COUPLING_SET
  if (*ok && coupling >= 0) *ok = vorbis_encode_ctl(&vi, OV_ECTL_COUPLING_SET, &coupling) == 0;
#else
  if (coupling >= 0) *ok = 0;
#endif
  if (*ok && lowpass > 0) *ok = vorbis_encode_ctl(&vi, OV_ECTL_LOWPASS_SET, &lowpass) == 0;
  if (*ok) *ok = vorbis_encode_setup_init(&vi) == 0;
  if (*ok) {
    char path[1024];
    FILE *f;
    vorbis_comment_init(&vc);
    vorbis_analysis_init(&vd, &vi);
    vorbis_analysis_headerout(&vd, &vc, &h, &hc, &hs);
    c = crc32(hs.packet, hs.bytes);
    snprintf(path, sizeof path, "%s/%08lx.bin", dir, c);
    if (!(f = fopen(path, "rb"))) {
      f = fopen(path, "wb");
      fwrite(hs.packet, 1, hs.bytes, f);
    }
    fclose(f);
    vorbis_dsp_clear(&vd);
    vorbis_comment_clear(&vc);
  }
  vorbis_info_clear(&vi);
  return c;
}

int main(int argc, char **argv) {
  if (argc < 7 || argc > 9) {
    fprintf(stderr, "usage: setups OUTDIR CH RATE QLO QHI QSTEP\n");
    return 2;
  }
  for (unsigned long i = 0; i < 256; i++) {
    unsigned long c = i;
    for (int k = 0; k < 8; k++) c = c & 1 ? 0xedb88320UL ^ (c >> 1) : c >> 1;
    crc_table[i] = c;
  }
  const char *dir = argv[1];
  int ch = atoi(argv[2]);
  long rate = atol(argv[3]);
  if (argc > 7) coupling = atoi(argv[7]);
  if (argc > 8) lowpass = atof(argv[8]);
  double lo = atof(argv[4]), hi = atof(argv[5]), step = atof(argv[6]);
  unsigned long prev = 1;
  for (long i = 0; lo + i * step <= hi + 1e-9; i++) {
    float q = (float)(lo + i * step);
    int ok;
    unsigned long c = setup(dir, ch, rate, q, &ok);
    if (c != prev || !ok) printf("%ld\t%d\t%.6f\t%s%08lx\n", rate, ch, q, ok ? "" : "-", c);
    prev = ok ? c : 1;
  }
  return 0;
}
