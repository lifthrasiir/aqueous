"""Generate codecs/aqr-div3/src/tables.rs from the probed tables (scripts/div3-probe)."""
import sys, os, json
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'div3-probe'))
import div3
from div3 import *
H = os.path.join(os.path.dirname(__file__), 'div3-probe')
def J(n): return json.load(open(os.path.join(H, n)))
out = []
def emit(s): out.append(s)
def vlc(name, items, doc=None):
    """items: [(code string, sym)] -> a table sorted by the left-aligned code."""
    rows = []
    for c, s in items:
        assert len(c) <= 32
        rows.append((int(c, 2) << (32 - len(c)), len(c), s))
    rows.sort()
    if doc: emit('/// ' + doc)
    emit('pub static %s: [(u32, u8, u16); %d] = [' % (name, len(rows)))
    for i in range(0, len(rows), 6):
        emit('    ' + ' '.join('(0x%08x, %d, %d),' % r for r in rows[i:i + 6]))
    emit('];')
ESC = 0xFFFF
emit('//! Generated by scripts/div3-gen.py from the tables probed out of ffmpeg\'s decoder; do not edit.')
emit('//! Every VLC is `(code left-aligned to 32 bits, length, symbol)`, sorted by code; the escape has symbol 0xFFFF.')
emit('')
# DC
for k in ('luma0', 'luma1', 'chroma0', 'chroma1'):
    d = div3.DC[k]
    items = [(c, l) for c, l in d['codes'].items()] + [(d['escape'], ESC)]
    vlc('DC_' + k.upper(), items, 'DC levels 0..118 (the symbol is the level); the escape is followed by 8 raw bits.')
# AC tables
def ac(name, tab):
    items = []; info = []
    for c, (run, lvl, last) in sorted(tab.codes.items()):
        items.append((c, len(info))); info.append((run, lvl, last))
    items.append((tab.esc, ESC))
    vlc(name + '_VLC', items)
    emit('pub static %s_INFO: [(u8, u8, u8); %d] = [' % (name, len(info)))
    for i in range(0, len(info), 8): emit('    ' + ' '.join('(%d, %d, %d),' % r for r in info[i:i + 8]))
    emit('];')
for i in range(3):
    ac('AC_INTRA%d' % i, div3.L[i])
for i in range(3):
    ac('AC_B%d' % i, div3.C[i])
# I-frame CBP: symbol = the coded-flag symbol of the first macroblock
items = [(c, div3.to_symbol(F, 0)) for c, F in div3.CBP_FLAGS.items()]
vlc('CBP_I', items, 'I-frame coded-block symbol (flags xor their prediction).')
# P macroblock types: symbol = flags | intra << 6
mbi = [(c, V) for c, V in div3.MBI.items()] + [(c, V | 64) for c, V in div3.MBA.items()]
vlc('MB_P', mbi, 'P-frame macroblock type: coded flags of the six blocks (bit 5 = block 0), bit 6 = intra.')
# MV
for t in (0, 1):
    tab = div3.MVT[t]
    items = []; vec = []
    for c, v in sorted(tab['codes'].items()):
        items.append((c, len(vec))); vec.append(tuple(v) if v else (0, 0))
    items.append((tab['esc'], ESC))
    vlc('MV%d_VLC' % t, items)
    emit('pub static MV%d_VEC: [(i8, i8); %d] = [' % (t, len(vec)))
    for i in range(0, len(vec), 8): emit('    ' + ' '.join('(%d, %d),' % (max(-127, min(127, a)), max(-127, min(127, b))) for a, b in vec[i:i + 8]))
    emit('];')
open(os.path.join(os.path.dirname(__file__), '..', 'codecs', 'aqr-div3', 'src', 'tables.rs'), 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
