"""Generate codecs/aqr-div3/src/ac3_tables.rs from scripts/ac3-probe/ac3_tables.json (the tables of ATSC A/52)."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(H, 'ac3-probe', 'ac3_tables.json')))
out = ['//! Generated by scripts/ac3-gen.py from the tables of ATSC A/52 (scripts/ac3-probe/extract_tables.py); do not edit.', '']
def arr(name, ty, vals, doc):
    out.append('/// ' + doc)
    out.append('pub static %s: [%s; %d] = [' % (name, ty, len(vals)))
    for i in range(0, len(vals), 12): out.append('    ' + ' '.join('%d,' % v for v in vals[i:i + 12]))
    out.append('];')
arr('FRAME_WORDS', '[u16; 3]', [], '')  # placeholder removed below
out = out[:2]
out.append('/// Words (16 bits) of a syncframe by frmsizecod, for fscod 0, 1 and 2 (48, 44.1 and 32 kHz).')
out.append('pub static FRAME_WORDS: [[u16; 3]; 38] = [')
for r in T['frame_words']: out.append('    [%d, %d, %d],' % tuple(r))
out.append('];')
arr('BNDTAB', 'u16', T['bndtab'], 'First mantissa of each of the 50 bands.')
arr('BNDSZ', 'u16', T['bndsz'], 'Width of each band.')
arr('LATAB', 'i32', T['latab'], 'Log-addition table.')
out.append('/// Hearing threshold by band, for fscod 0, 1 and 2.')
out.append('pub static HTH: [[i32; 3]; 50] = [')
for r in T['hth']: out.append('    [%d, %d, %d],' % tuple(r))
out.append('];')
arr('BAPTAB', 'u8', T['baptab'], 'Bit allocation pointer by address.')
arr('SLOWDEC', 'i32', T['slowdec'], 'Slow decay.')
arr('FASTDEC', 'i32', T['fastdec'], 'Fast decay.')
arr('SLOWGAIN', 'i32', T['slowgain'], 'Slow gain.')
arr('DBPBTAB', 'i32', T['dbpbtab'], 'dB per bit.')
arr('FLOORTAB', 'i32', T['floortab'], 'Floor.')
arr('FASTGAIN', 'i32', T['fastgain'], 'Fast gain.')
open(os.path.join(H, '..', 'codecs', 'aqr-div3', 'src', 'ac3_tables.rs'), 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
