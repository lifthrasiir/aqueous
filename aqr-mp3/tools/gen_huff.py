#!/usr/bin/env python3
"""Generates src/huff_tables.rs from minimp3.h (CC0) by walking its Huffman decoding trees.

Usage: gen_huff.py path/to/minimp3.h > src/huff_tables.rs
"""
import re, sys

src = open(sys.argv[1]).read()

def arr(name):
    m = re.search(r'static const \w+ ' + name + r'\[[^\]]*\]\s*=\s*\{(.*?)\};', src, re.S)
    return [int(x) for x in m.group(1).replace('\n', ' ').split(',') if x.strip()]

tabs, tab32, tab33 = arr('tabs'), arr('tab32'), arr('tab33')
tabindex, linbits = arr('tabindex'), arr('g_linbits')

def walk(base):
    """Returns {(x, y): (code, len)} for the pair table at tabs[base]."""
    out = {}
    def rec(off, w, prefix, plen):
        for v in range(1 << w):
            leaf = tabs[base + off + v]
            if leaf >= 0:
                n = leaf >> 8
                assert 0 < n <= w
                code = (prefix << n) | (v >> (w - n))
                key = (leaf & 15, (leaf >> 4) & 15)
                if key in out:
                    assert out[key] == (code, plen + n), (key, out[key], code, plen + n)
                else:
                    out[key] = (code, plen + n)
            else:
                rec(-(leaf >> 3), leaf & 7, (prefix << w) | v, plen + w)
    rec(0, 5, 0, 0)
    return out

def walk_count1(t):
    out = {}
    for v in range(16):
        leaf = t[v]
        if leaf & 8:
            n = leaf & 7
            code = v >> (4 - n)
            key = leaf >> 4
            assert out.get(key, (code, n)) == (code, n)
            out[key] = (code, n)
        else:
            k = leaf & 3
            for u in range(1 << k):
                leaf2 = t[(leaf >> 3) + u]
                n = leaf2 & 7
                full = (v << k) | u
                code = full >> (4 + k - n)
                key = leaf2 >> 4
                assert out.get(key, (code, n)) == (code, n)
                out[key] = (code, n)
    return out

def check_prefix(codes):
    # Kraft equality: the MP3 tables are complete prefix codes.
    s = sum(2.0 ** -n for (_, n) in codes.values())
    lst = sorted(codes.values(), key=lambda c: c[1])
    for i, (a, n) in enumerate(lst):
        for (b, m) in lst[i + 1:]:
            assert (b >> (m - n)) != a, 'not a prefix code'
    return s

print('// Generated by tools/gen_huff.py from minimp3.h (CC0). Do not edit.')
print('// Big-values tables: index = x * 16 + y, entry = (code << 5) | len, 0 = absent.')
print('// Tables 4 and 14 do not exist; 16..23 and 24..31 share codes (different linbits).')
print()
print('pub static LINBITS: [u8; 32] = [%s];' % ', '.join(map(str, linbits)))
print()
seen = {}
names = []
for t in range(32):
    if t == 0 or t in (4, 14):
        names.append(None)
        continue
    base = tabindex[t]
    if base in seen:
        names.append(seen[base])
        continue
    codes = walk(base)
    k = check_prefix(codes)
    assert abs(k - 1.0) < 1e-12, (t, k)
    dim = 1 + max(max(x, y) for (x, y) in codes)
    assert len(codes) == dim * dim, (t, dim, len(codes))
    name = 'T%d' % t
    seen[base] = name
    names.append(name)
    ent = [0] * 256
    for (x, y), (c, n) in codes.items():
        assert n <= 19
        ent[x * 16 + y] = (c << 5) | n
    print('/// Table %d: %dx%d, max code length %d.' % (t, dim, dim, max(n for _, n in codes.values())))
    print('static %s: [u32; 256] = [' % name)
    for i in range(0, 256, 16):
        print('    ' + ', '.join(str(e) for e in ent[i:i + 16]) + ',')
    print('];')
print()
print('/// Pair tables by table_select (None for 0, 4 and 14).')
print('pub static PAIR: [Option<&[u32; 256]>; 32] = [%s];' %
      ', '.join('None' if n is None else 'Some(&%s)' % n for n in names))
dims = []
for t in range(32):
    if names[t] is None:
        dims.append(0 if t == 0 else 0)
    else:
        dims.append(16 if t >= 16 else 1 + max(max(x, y) for (x, y) in walk(tabindex[t])))
print('/// Alphabet size per coordinate (0 for missing tables).')
print('pub static DIM: [u8; 32] = [%s];' % ', '.join(map(str, dims)))
print()
for nm, t in (('COUNT1A', tab32), ('COUNT1B', tab33)):
    codes = walk_count1(t)
    assert len(codes) == 16
    assert abs(check_prefix(codes) - 1.0) < 1e-12
    print('/// Count1 table %s: index = v<<3 | w<<2 | x<<1 | y, entry = (code << 5) | len.' % nm[-1])
    print('pub static %s: [u32; 16] = [%s];' % (nm, ', '.join(str((codes[k][0] << 5) | codes[k][1]) for k in range(16))))
